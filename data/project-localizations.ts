export function localizeProject(project: Project, locale: Locale): Project {
  if (locale === "en") return project;

  const translation = projectTranslationsAr[project.slug];
  return translation ? { ...project, ...translation } : project;
}

export function localizeProjects(projects: Project[], locale: Locale): Project[] {
  return projects.map((project) => localizeProject(project, locale));
}

export function localizeSecondaryProjects(
  projects: SecondaryProject[],
  locale: Locale,
): SecondaryProject[] {
  if (locale === "en") return projects;

  return projects.map((project) => ({
    ...project,
    description: secondaryDescriptionsAr[project.title] ?? project.description,
  }));
}
